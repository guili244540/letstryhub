import { defineConfig } from 'vite';
import { copyFileSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';

// Serves the favicon (src/flowchart.svg, the single source) at
// /flowchart.svg in dev and copies it into dist/ at build time, so the
// <link rel="icon"> of the Vite pages works on both surfaces without a
// duplicate copy in public/ (which Vite forbids importing from JS).
function serveFavicon() {
  const file = resolve(__dirname, 'src', 'flowchart.svg');
  let outDir;
  return {
    name: 'serve-favicon',
    configResolved(config) {
      outDir = config.build.outDir;
    },
    configureServer(server) {
      server.middlewares.use('/flowchart.svg', (req, res) => {
        res.setHeader('Content-Type', 'image/svg+xml');
        res.end(readFileSync(file));
      });
    },
    closeBundle() {
      copyFileSync(file, resolve(outDir, 'flowchart.svg'));
    }
  };
}

// Copies the fully standalone editor page (page/bpmnEditor.html,
// generated by npm run inline-lib) next to the built app bundle, so a
// deployed dist/ site can offer it as a one-click download from the
// editor app header. A second, extensionless copy exists because some
// browsers/extensions rewrite requests by stripping the .html suffix;
// plain file servers (python3 -m http.server) then 404. The button
// handler retries the extensionless path when the first fetch fails.
function copyStandaloneEditor() {
  let outDir;
  return {
    name: 'copy-standalone-editor',
    configResolved(config) {
      outDir = config.build.outDir;
    },
    closeBundle() {
      for (const name of ['bpmnEditor.html', 'bpmnEditor']) {
        copyFileSync(
          resolve(__dirname, 'page', 'bpmnEditor.html'),
          resolve(outDir, name)
        );
      }
    }
  };
}

export default defineConfig({
  plugins: [copyStandaloneEditor(), serveFavicon()],
  build: {
    chunkSizeWarningLimit: 2048,
    rollupOptions: {
      input: {
        main: new URL('./index.html', import.meta.url).pathname,
        viewer: new URL('./viewer.html', import.meta.url).pathname
      }
    }
  }
});
